import numpy as np
import matplotlib.pyplot as plt
import argparse
import poly
from sklearn.model_selection import train_test_split
from sklearn.model_selection import KFold
from sklearn.linear_model import Ridge
if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--noise", type=float, default=200)
    parser.add_argument("--poly_seed", type=int, default=42)
    parser.add_argument("--p_seed", type=int, default=42)
    parser.add_argument("--split_seed", type=int, default=42)
    args = parser.parse_args()

    noise = args.noise
    poly_seed = args.poly_seed
    p_seed = args.p_seed
    split_seed = args.split_seed
    true_coefs = np.array([8,6,4,0.3])
    X, y = poly.make_poly_data(n=500, seed=poly_seed, x_low=0, x_high=20, true_coefs=true_coefs, noise=noise)
    print("Variance of X(degree=3):", poly.variation(X, degree=3))
    X_train, X_test, y_train, y_test = train_test_split(X, y, test_size=0.2, random_state=split_seed)
    splitter = KFold(5,shuffle=True, random_state=p_seed) 
    fig, axs = plt.subplots(2, 4, figsize=(20, 8))
    model = Ridge()
    pipelines = poly.build_pipelines(degree=9)
    scale_first = pipelines["scale_first"]
    scale_afterpoly = pipelines["scale_afterpoly"]
    scale_both = pipelines["scale_both"]
    b = poly.curve_for(model, X_train, y_train, np.logspace(-4, 3, 50), cv=splitter,scoring="neg_root_mean_squared_error", parameter="alpha")
    sf = poly.curve_for(scale_first, X_train, y_train, np.logspace(-4, 3, 50),scoring="neg_root_mean_squared_error", cv=splitter)
    sl = poly.curve_for(scale_afterpoly, X_train, y_train, np.logspace(-4, 3, 50),scoring="neg_root_mean_squared_error", cv=splitter)
    sb = poly.curve_for(scale_both, X_train, y_train, np.logspace(-4, 3, 50),scoring="neg_root_mean_squared_error", cv=splitter)

    poly.plot_curve(b,parameter="alpha", ax=axs[0, 0], score="Negative Root Mean Squared Error")
    poly.plot_curve(sf,parameter="ridge__alpha", ax=axs[0, 1], score="Negative Root Mean Squared Error")
    poly.plot_curve(sl,parameter="ridge__alpha", ax=axs[0, 2], score="Negative Root Mean Squared Error")
    poly.plot_curve(sb, parameter="ridge__alpha", ax=axs[0, 3], score="Negative Root Mean Squared Error")
    axs[0, 0].set_title("Base Model")
    axs[0, 1].set_title("Scale First")
    axs[0, 2].set_title("Scale After Polynomial")
    axs[0, 3].set_title("Scale Both")


    X_2, y_2 = poly.make_poly_data(n=60, seed=poly_seed, x_low=0, x_high=20, true_coefs=true_coefs, noise=noise)
    print("Variance of X_2(small dataset and degree=3):", poly.variation(X_2, degree=3))
    X_train2, X_test2, y_train2, y_test2 = train_test_split(X_2, y_2, test_size=0.2, random_state=split_seed)
    b2 = poly.curve_for(model=model, X_train=X_train2, y_train=y_train2, alphas=np.logspace(-4, 3, 50), cv=splitter, parameter="alpha",scoring="neg_root_mean_squared_error")
    sf2 = poly.curve_for(scale_first, X_train2, y_train2, np.logspace(-4, 3, 50), cv=splitter, scoring="neg_root_mean_squared_error")
    sl2 = poly.curve_for(scale_afterpoly, X_train2, y_train2, np.logspace(-4, 3, 50), cv=splitter, scoring="neg_root_mean_squared_error")
    sb2 = poly.curve_for(scale_both, X_train2, y_train2, np.logspace(-4, 3, 50), cv=splitter, scoring="neg_root_mean_squared_error")
    
    poly.plot_curve(result=b2, ax=axs[1, 0], parameter="alpha", score="Negative Root Mean Squared Error")
    poly.plot_curve(sf2, ax=axs[1, 1], score="Negative Root Mean Squared Error")
    poly.plot_curve(sl2, ax=axs[1, 2], score="Negative Root Mean Squared Error")
    poly.plot_curve(sb2, ax=axs[1, 3], score="Negative Root Mean Squared Error")
    axs[1, 0].set_title("Small Dataset Base Model")
    axs[1, 1].set_title("Small Dataset Scale First")
    axs[1, 2].set_title("Small Dataset Scale After Polynomial")
    axs[1, 3].set_title("Small Dataset Scale Both")
    fig.tight_layout()

    sf_besta=poly.best_alpha(sf)
    sl_besta=poly.best_alpha(sl)
    sb_besta=poly.best_alpha(sb)
    base_besta = poly.best_alpha(b)
    base_test = poly.final_test_score(model, X_train, y_train,X_test, y_test, best_alpha=base_besta, scoring='neg_root_mean_squared_error')
    sf_test = poly.final_test_score(scale_first, X_train, y_train,X_test, y_test, best_alpha=sf_besta, scoring='neg_root_mean_squared_error')
    sl_test = poly.final_test_score(scale_afterpoly, X_train, y_train,X_test, y_test, best_alpha=sl_besta, scoring='neg_root_mean_squared_error')
    sb_test = poly.final_test_score(scale_both, X_train, y_train,X_test, y_test, best_alpha=sb_besta, scoring='neg_root_mean_squared_error')
    big_rnoise = poly.realized_noise_rms(X_test, y_test, [8,6,4,0.3])
    big_base_rmse, big_base_std = poly.cv_rmse_at(b, base_besta,ddof=1, scoring='neg_root_mean_squared_error') 
    big_sf_rmse, big_sf_std = poly.cv_rmse_at(sf, sf_besta,ddof=1, scoring='neg_root_mean_squared_error')
    big_sl_rmse, big_sl_std = poly.cv_rmse_at(sl, sl_besta,ddof=1, scoring='neg_root_mean_squared_error')
    big_sb_rmse, big_sb_std = poly.cv_rmse_at(sb, sb_besta,ddof=1, scoring='neg_root_mean_squared_error')
    big_cv_rmse = poly.cv_rmse_per_fold(splitter, y_train-poly.polyval(X_train.ravel(), true_coefs))
    
    print(f"Base Model best alpha: {base_besta} Test Score: {abs(base_test)} Noise Floor:{big_rnoise} RMSE at best alpha:{big_base_rmse} Fold to Fold STD: {big_base_std} Train set floor: {big_cv_rmse}")
    print(f"Scale First best alpha: {sf_besta} Test Score: {abs(sf_test)} Noise Floor: {big_rnoise} RMSE at best alpha:{big_sf_rmse}  Fold to Fold STD: {big_sf_std} Train set floor: {big_cv_rmse}")
    print(f'Scale after Polynomial best alpha: {sl_besta} Test Score: {abs(sl_test)} Noise Floor: {big_rnoise} RMSE at best alpha:{big_sl_rmse} Fold to Fold STD: {big_sl_std} Train set floor: {big_cv_rmse}')
    print(f'Scale both best alpha: {sb_besta} Test Score: {abs(sb_test)} Noise Floor {big_rnoise} RMSE at best alpha:{big_sb_rmse} Fold to Fold STD: {big_sb_std} Train set floor: {big_cv_rmse}')
    for ax in axs[0]:
        ax.grid(True)
        ax.set_xscale("log")
        poly.add_noise_floor(ax, big_cv_rmse)
        ax.legend()
        ax.legend().get_texts()[1].set_text('Validation')
    
    base_besta2 = poly.best_alpha(b2)
    sf_besta2 = poly.best_alpha(sf2)
    sl_besta2 = poly.best_alpha(sl2)
    sb_besta2 = poly.best_alpha(sb2)
    base_test2 = poly.final_test_score(model, X_train2, y_train2,X_test2, y_test2, best_alpha=base_besta2, scoring='neg_root_mean_squared_error')
    sf_test2 = poly.final_test_score(scale_first, X_train2, y_train2,X_test2, y_test2, best_alpha=sf_besta2, scoring='neg_root_mean_squared_error')
    sl_test2 = poly.final_test_score(scale_afterpoly, X_train2, y_train2,X_test2, y_test2, best_alpha=sl_besta2, scoring='neg_root_mean_squared_error')
    sb_test2 = poly.final_test_score(scale_both, X_train2, y_train2,X_test2, y_test2, best_alpha=sb_besta2, scoring='neg_root_mean_squared_error')   
    small_rnoise = poly.realized_noise_rms(X_test2, y_test2, [8,6,4,0.3])
    small_base_rmse, small_base_std = poly.cv_rmse_at(b2, base_besta2,ddof=1, scoring='neg_root_mean_squared_error') 
    small_sf_rmse, small_sf_std = poly.cv_rmse_at(sf2, sf_besta2,ddof=1, scoring='neg_root_mean_squared_error')
    small_sl_rmse, small_sl_std = poly.cv_rmse_at(sl2, sl_besta2,ddof=1, scoring='neg_root_mean_squared_error')
    small_sb_rmse, small_sb_std = poly.cv_rmse_at(sb2, sb_besta2,ddof=1, scoring='neg_root_mean_squared_error')
    small_cv_rmse = poly.cv_rmse_per_fold(splitter, y_train2-poly.polyval(X_train2.ravel(), true_coefs))
    
    print(f"Small Dataset Base Model best alpha: {base_besta2} Test Score: {abs(base_test2)} Noise Floor: {small_rnoise} RMSE at best alpha: {small_base_rmse} Fold to Fold STD: {small_base_std} Train set floor: {small_cv_rmse}")
    print(f"Small Dataset Scale First best alpha: {sf_besta2} Test Score: {abs(sf_test2)} Noise Floor: {small_rnoise} RMSE at best alpha: {small_sf_rmse}  Fold to Fold STD: {small_sf_std} Train set floor: {small_cv_rmse}")
    print(f'Small Dataset Scale after Polynomial best alpha: {sl_besta2} Test Score: {abs(sl_test2)} Noise Floor: {small_rnoise} RMSE at best alpha: {small_sl_rmse}  Fold to Fold STD: {small_sl_std} Train set floor: {small_cv_rmse}')
    print(f'Small Dataset Scale both best alpha: {sb_besta2} Test Score: {abs(sb_test2)} Noise Floor: {small_rnoise} RMSE at best alpha: {small_sb_rmse} Fold to Fold STD: {small_sb_std} Train set floor: {small_cv_rmse}')
    for ax in axs[1]:
        ax.grid(True)
        ax.set_xscale("log")
        ax.set_ylabel("Negative Root Mean Squared Error")
        poly.add_noise_floor(ax, small_cv_rmse)
        ax.legend()
        ax.legend().get_texts()[1].set_text('Validation')
    fige, axe =plt.subplots(1,2,figsize=(14,6), sharey='col')
    poly.plot_curve(sf,parameter="ridge__alpha", ax=axe[0], score="Negative Root Mean Squared Error")
    poly.plot_curve(sl,parameter="ridge__alpha", ax=axe[0], score="Negative Root Mean Squared Error")
    poly.plot_curve(sb, parameter="ridge__alpha", ax=axe[0], score="Negative Root Mean Squared Error")
    axe[0].grid(True)
    poly.add_noise_floor(axe[0], big_cv_rmse)
    axe[0].set_title("Big Dataset Pipeline Curves")
    axe[0].lines[0].remove()
    axe[0].lines[1].remove()
    axe[0].lines[2].remove()
    legend2 =axe[0].legend()
    legend2.get_texts()[0].set_text('Scale First Validation')
    legend2.get_texts()[1].set_text('Scale after poly Validation')
    legend2.get_texts()[2].set_text('Scale Both Validation')
    axe[0].set_ylim(-big_cv_rmse-20, -big_cv_rmse+20)
    poly.plot_curve(sf2,parameter='ridge__alpha', ax=axe[1], score="Negative Root Mean Squared Error")
    poly.plot_curve(sl2,parameter='ridge__alpha', ax=axe[1], score="Negative Root Mean Squared Error")
    poly.plot_curve(sb2,parameter='ridge__alpha', ax=axe[1],score="Negative Root Mean Squared Error")
    axe[1].grid(True)
    poly.add_noise_floor(axe[1], small_cv_rmse)
    axe[1].set_title("Small Dataset Pipeline Curves")
    axe[1].lines[0].remove()
    axe[1].lines[1].remove()
    axe[1].lines[2].remove()
    legend3 =axe[1].legend()
    legend3.get_texts()[0].set_text('Scale First Validation')
    legend3.get_texts()[1].set_text('Scale after poly Validation')
    legend3.get_texts()[2].set_text('Scale Both Validation')
    axe[1].set_ylim(-small_cv_rmse-20, -small_cv_rmse+20)
    fige.tight_layout()
    plt.show()
    s1 = poly.placement(scale_first, X_train, y_train)
    s2 = poly.placement(scale_afterpoly, X_train, y_train)
    s3 = poly.placement(scale_both, X_train, y_train)
    s4 = poly.placement(scale_first, X_train2, y_train2)
    s5 = poly.placement(scale_afterpoly, X_train2, y_train2)
    s6 = poly.placement(scale_both, X_train2, y_train2)
    print(f'Variances: {s1[0]} Condition: {s1[1]}, Max Absolute Correlation: {s1[2]}')
    print(f'Variances: {s2[0]} Condition: {s2[1]}, Max Absolute Correlation: {s2[2]}')
    print(f'Variances: {s3[0]} Condition: {s3[1]}, Max Absolute Correlation: {s3[2]}')
    print(f'Variances: {s4[0]} Condition: {s4[1]}, Max Absolute Correlation: {s4[2]}')
    print(f'Variances: {s5[0]} Condition: {s5[1]}, Max Absolute Correlation: {s5[2]}')
    print(f'Variances: {s6[0]} Condition: {s6[1]}, Max Absolute Correlation: {s6[2]}')
    b1 = poly.bias_results(scale_first, 'polynomial', 'ridge', X_train, y_train, X_test)
    b2 = poly.bias_results(scale_afterpoly, 'polynomial', 'ridge', X_train, y_train, X_test)
    b3 = poly.bias_results(scale_both, 'polynomial', 'ridge', X_train, y_train, X_test)
    b4 = poly.bias_results(scale_first, 'polynomial', 'ridge', X_train2, y_train2, X_test2)
    b5 = poly.bias_results(scale_afterpoly, 'polynomial', 'ridge', X_train2, y_train2, X_test2)
    b6 = poly.bias_results(scale_both, 'polynomial', 'ridge', X_train2, y_train2, X_test2)
    print(f'Bias: {b1[0]} Max Residual: {b1[1]}')
    print(f'Bias: {b2[0]} Max Residual: {b2[1]}')
    print(f'Bias: {b3[0]} Max Residual: {b3[1]}')
    print(f'Bias: {b4[0]} Max Residual: {b4[1]}')
    print(f'Bias: {b5[0]} Max Residual: {b5[1]}')
    print(f'Bias: {b6[0]} Max Residual: {b6[1]}')
